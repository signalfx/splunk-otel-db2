package com.splunk.otel.db2.receiver.queries;

import io.opentelemetry.api.common.AttributeKey;
import io.opentelemetry.api.common.Attributes;
import io.opentelemetry.api.common.AttributesBuilder;
import io.opentelemetry.api.logs.Logger;
import io.opentelemetry.api.logs.Severity;
import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import io.opentelemetry.context.Context;

import java.time.Instant;
import java.util.concurrent.TimeUnit;

/**
 * Typed builder for a {@code db.server.query_sample} OTel log record.
 *
 * Centralises all attribute keys in one place — analogous to the typed
 * {@code RecordDbServerQuerySampleEvent} method generated by mdatagen in
 * the Go OTel Collector receiver ecosystem.
 *
 * Severity is INFO for normal active sessions and WARN when a MON_LOCKWAITS
 * row matched (i.e. when waitDurationSec is set), regardless of whether the
 * holder identity is available.
 */
public final class QuerySampleEvent {

    public static final AttributeKey<String> DB_SYSTEM        = AttributeKey.stringKey("db.system.name");
    public static final AttributeKey<String> DB_NAMESPACE     = AttributeKey.stringKey("db.namespace");
    public static final AttributeKey<String> DB_QUERY_TEXT    = AttributeKey.stringKey("db.query.text");
    public static final AttributeKey<String> DB_OPERATION     = AttributeKey.stringKey("db.operation.name");
    public static final AttributeKey<String> DB2_APP_HANDLE      = AttributeKey.stringKey("db2.session_id");
    public static final AttributeKey<String> DB2_ACTIVITY        = AttributeKey.stringKey("db2.activity_state");
    public static final AttributeKey<String> DB2_SESSION_STATUS  = AttributeKey.stringKey("db2.session_status");
    public static final AttributeKey<String> DB2_PLAN_HASH       = AttributeKey.stringKey("db2.query_plan.hash");
    public static final AttributeKey<String> DB2_QUERY_START     = AttributeKey.stringKey("db2.query_start");
    public static final AttributeKey<Double> DB2_DURATION     = AttributeKey.doubleKey("db2.session.duration");
    public static final AttributeKey<Long>   DB2_MEMBER       = AttributeKey.longKey("db2.member");
    public static final AttributeKey<Double> DB2_CPU_TIME     = AttributeKey.doubleKey("db2.cpu_time");
    public static final AttributeKey<Double> DB2_WAIT_TIME    = AttributeKey.doubleKey("db2.wait_time");
    public static final AttributeKey<String> USER_NAME        = AttributeKey.stringKey("user.name");
    public static final AttributeKey<String> CLIENT_ADDRESS   = AttributeKey.stringKey("client.address");

    // Blocking session attributes — populated only when this session is in lock-wait.
    public static final AttributeKey<String>  DB2_BLOCKER_APP_HANDLE = AttributeKey.stringKey("db2.blocking.blocker.session_id");
    public static final AttributeKey<String>  DB2_BLOCKER_USER       = AttributeKey.stringKey("db2.blocking.blocker.user");
    public static final AttributeKey<String>  DB2_BLOCKER_HOST       = AttributeKey.stringKey("db2.blocking.blocker.client_address");
    public static final AttributeKey<String>  DB2_BLOCKER_QUERY_TEXT = AttributeKey.stringKey("db2.blocking.blocker.query_text");
    public static final AttributeKey<Boolean> DB2_BLOCKER_IS_IDLE    = AttributeKey.booleanKey("db2.blocking.blocker.is_idle");
    public static final AttributeKey<String>  DB2_LOCK_OBJECT_TYPE   = AttributeKey.stringKey("db2.blocking.lock.object_type");
    public static final AttributeKey<String>  DB2_LOCK_MODE          = AttributeKey.stringKey("db2.blocking.lock.mode");
    public static final AttributeKey<String>  DB2_LOCK_OBJECT_NAME   = AttributeKey.stringKey("db2.blocking.lock.object_name");
    public static final AttributeKey<String>  DB2_LOCK_SCHEMA        = AttributeKey.stringKey("db2.blocking.lock.schema");
    public static final AttributeKey<String>  DB2_BLOCKING_START     = AttributeKey.stringKey("db2.blocking.start_time");
    public static final AttributeKey<Double>  DB2_WAIT_DURATION      = AttributeKey.doubleKey("db2.blocking.wait_duration");

    // Required
    private final String dbNamespace;
    private final String queryText;
    private final double sessionDurationSec;
    private final long   member;

    // Optional — query sample fields
    private String appHandle;
    private String activityState;
    private String sessionStatus;
    private String operationName;
    private String queryStart;
    private String userName;
    private String clientAddress;
    private Double cpuTimeSec;   // null = omit (snapshot path has no CPU data)
    private Double waitTimeSec;  // null = omit (Db2 < 10.5 has no MON_GET_ACTIVITY)
    private String planHash;  // null = not available (snapshot path or no active section)

    // Optional — blocking fields (null = not in lock-wait)
    private String  blockerHandle;
    private String  blockerUser;
    private String  blockerHost;
    private String  blockerQueryText;
    private Boolean blockerIsIdle;
    private String  lockObjectType;
    private String  lockMode;
    private String  lockObjectName;
    private String  lockSchema;
    private String  blockingStartTime;
    private Double  waitDurationSec;
    private boolean blocked;
    private SpanContext spanContext;

    private QuerySampleEvent(String dbNamespace, String queryText,
                             double sessionDurationSec, long member) {
        this.dbNamespace        = dbNamespace;
        this.queryText          = queryText;
        this.sessionDurationSec = sessionDurationSec;
        this.member             = member;
    }

    public static QuerySampleEvent of(String dbNamespace, String queryText,
                                      double sessionDurationSec, long member) {
        return new QuerySampleEvent(dbNamespace, queryText, sessionDurationSec, member);
    }

    public QuerySampleEvent appHandle(String v)      { this.appHandle      = v; return this; }
    public QuerySampleEvent activityState(String v)  { this.activityState  = v; return this; }
    public QuerySampleEvent sessionStatus(String v)  { this.sessionStatus  = v; return this; }
    public QuerySampleEvent operationName(String v)  { this.operationName  = v; return this; }
    public QuerySampleEvent queryStart(String v)     { this.queryStart     = v; return this; }
    public QuerySampleEvent userName(String v)       { this.userName      = v; return this; }
    public QuerySampleEvent clientAddress(String v)  { this.clientAddress = v; return this; }

    /** Pass cpu time in microseconds; stored as seconds. Pass -1 to omit. */
    public QuerySampleEvent cpuTimeMicros(long cpuUs) {
        if (cpuUs >= 0) this.cpuTimeSec = cpuUs / 1_000_000.0;
        return this;
    }

    /** Pass lock wait time in milliseconds; stored as seconds. Pass -1 to omit (Db2 < 10.5). */
    public QuerySampleEvent waitTimeMillis(long waitMs) {
        if (waitMs >= 0) this.waitTimeSec = waitMs / 1000.0;
        return this;
    }

    public QuerySampleEvent planHash(String v) { this.planHash = v; return this; }

    // Blocking attribute setters
    public QuerySampleEvent blockerHandle(String v)       { this.blockerHandle     = v; return this; }
    public QuerySampleEvent blockerUser(String v)         { this.blockerUser        = v; return this; }
    public QuerySampleEvent blockerHost(String v)         { this.blockerHost        = v; return this; }
    public QuerySampleEvent blockerQueryText(String v)    { this.blockerQueryText   = v; return this; }
    public QuerySampleEvent blockerIsIdle(Boolean v)      { this.blockerIsIdle      = v; return this; }
    public QuerySampleEvent lockObjectType(String v)      { this.lockObjectType     = v; return this; }
    public QuerySampleEvent lockMode(String v)            { this.lockMode           = v; return this; }
    public QuerySampleEvent lockObjectName(String v)      { this.lockObjectName     = v; return this; }
    public QuerySampleEvent lockSchema(String v)          { this.lockSchema         = v; return this; }
    public QuerySampleEvent blockingStartTime(String v)   { this.blockingStartTime  = v; return this; }
    public QuerySampleEvent waitDurationSeconds(double sec) {
        if (sec >= 0) this.waitDurationSec = sec;
        return this;
    }

    /**
     * Marks the session as lock-blocked independently of the wait duration.
     *
     * <p>Severity used to be derived from {@code waitDurationSec != null}, which conflated two
     * different facts: that a lock wait exists, and that its duration is known. A matched
     * MON_LOCKWAITS row with a NULL elapsed time is still a confirmed block, and reporting it at
     * INFO while carrying blocking attributes understates a real problem.
     */
    public QuerySampleEvent blocked(boolean v) { this.blocked = v; return this; }

    /**
     * Links this event to the trace the sampled application was running under, as read from the
     * session's CLIENT_ACCTNG traceparent. Null when the application did not propagate one.
     */
    public QuerySampleEvent spanContext(SpanContext v) { this.spanContext = v; return this; }

    public void emit(Logger logger, Instant timestamp) {
        AttributesBuilder b = Attributes.builder()
            .put(DB_SYSTEM,    "ibm.db2")
            .put(DB_NAMESPACE, dbNamespace)
            .put(DB_QUERY_TEXT, queryText)
            .put(DB2_DURATION,  sessionDurationSec)
            .put(DB2_MEMBER,    member);

        if (appHandle     != null) b.put(DB2_APP_HANDLE,  appHandle);
        if (activityState != null) b.put(DB2_ACTIVITY,       activityState);
        if (sessionStatus != null) b.put(DB2_SESSION_STATUS, sessionStatus);
        if (operationName != null) b.put(DB_OPERATION,       operationName);
        if (queryStart    != null) b.put(DB2_QUERY_START, queryStart);
        if (userName      != null) b.put(USER_NAME,       userName);
        if (clientAddress != null) b.put(CLIENT_ADDRESS,  clientAddress);
        if (cpuTimeSec    != null) b.put(DB2_CPU_TIME,    cpuTimeSec);
        if (waitTimeSec   != null) b.put(DB2_WAIT_TIME,   waitTimeSec);
        if (planHash      != null) b.put(DB2_PLAN_HASH,   planHash);

        if (blockerHandle     != null) b.put(DB2_BLOCKER_APP_HANDLE, blockerHandle);
        if (blockerUser       != null) b.put(DB2_BLOCKER_USER,       blockerUser);
        if (blockerHost       != null) b.put(DB2_BLOCKER_HOST,       blockerHost);
        if (blockerQueryText  != null) b.put(DB2_BLOCKER_QUERY_TEXT, blockerQueryText);
        if (blockerIsIdle     != null) b.put(DB2_BLOCKER_IS_IDLE,    blockerIsIdle);
        if (lockObjectType    != null) b.put(DB2_LOCK_OBJECT_TYPE,   lockObjectType);
        if (lockMode          != null) b.put(DB2_LOCK_MODE,          lockMode);
        if (lockObjectName    != null) b.put(DB2_LOCK_OBJECT_NAME,   lockObjectName);
        if (lockSchema        != null) b.put(DB2_LOCK_SCHEMA,        lockSchema);
        if (blockingStartTime != null) b.put(DB2_BLOCKING_START,     blockingStartTime);
        if (waitDurationSec   != null) b.put(DB2_WAIT_DURATION,      waitDurationSec);

        // Blocked sessions are escalated to WARN so they stand out in OTel backends.
        // Driven by the explicit blocked flag, not by the presence of a duration: a matched
        // MON_LOCKWAITS row with a NULL elapsed time is still a confirmed block. waitDurationSec
        // is kept as a fallback for callers that only set the duration.
        boolean isBlocked = blocked || waitDurationSec != null;
        Severity severity = isBlocked ? Severity.WARN : Severity.INFO;

        io.opentelemetry.api.logs.LogRecordBuilder builder = logger.logRecordBuilder()
            .setEventName("db.server.query_sample")
            .setSeverity(severity)
            .setSeverityText(isBlocked ? "WARN" : "INFO")
            .setTimestamp(timestamp.toEpochMilli(), TimeUnit.MILLISECONDS)
            .setAllAttributes(b.build());

        // Always set the context, so the sampled query joins the application's trace when there is
        // one and is explicitly unparented when there is not. Leaving it unset is not neutral:
        // SdkLogRecordBuilder falls back to Context.current(), which would stamp whatever span
        // happens to be active on the collection thread onto every unlinked sample — the receiver's
        // own internal span under auto-instrumentation, for instance. Same reasoning as
        // mysqlreceiver's use of context.Background() for query samples.
        builder.setContext(spanContext != null
            ? Context.root().with(Span.wrap(spanContext))
            : Context.root());

        builder.emit();
    }
}
